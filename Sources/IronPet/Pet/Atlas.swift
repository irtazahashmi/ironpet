import AppKit

/// One animation row of a Codex v2 pet atlas.
struct AtlasRow: Equatable {
    let index: Int
    let durations: [Double]
    let loops: Bool

    static func uniform(_ index: Int, frames: Int, each: Double, last: Double, loops: Bool = true) -> AtlasRow {
        AtlasRow(index: index, durations: Array(repeating: each, count: frames - 1) + [last], loops: loops)
    }

    static let idle = AtlasRow(index: 0, durations: [0.28, 0.11, 0.11, 0.14, 0.14, 0.32], loops: true)
    static let runRight = uniform(1, frames: 8, each: 0.12, last: 0.22)
    static let runLeft = uniform(2, frames: 8, each: 0.12, last: 0.22)
    static let waving = uniform(3, frames: 4, each: 0.14, last: 0.28, loops: false)
    static let jumping = uniform(4, frames: 5, each: 0.14, last: 0.28, loops: false)
    static let failed = uniform(5, frames: 8, each: 0.14, last: 0.24)
    static let waiting = uniform(6, frames: 6, each: 0.15, last: 0.26)
    static let running = uniform(7, frames: 6, each: 0.12, last: 0.22)
    static let review = uniform(8, frames: 6, each: 0.15, last: 0.28)
    static let drinking = AtlasRow(index: 11, durations: [0.3, 0.3, 0.55, 0.55, 0.35, 0.9], loops: false)
    static let stretching = AtlasRow(index: 12, durations: [0.25, 0.25, 0.45, 0.45, 0.5, 0.5, 0.3, 0.6], loops: false)
}

/// Sliced frames of a Codex v2 atlas (1536x2288): rows 0-8 animations, rows 9-10 sixteen look directions.
/// ironpet's own art adds rows 11-12 (drinking, stretching), making it 1536x2704.
struct Atlas {
    static let cell = CGSize(width: 192, height: 208)
    static let width = 1536
    static let heights = [2288, 2704]

    let rows: [[CGImage]]
    let look: [CGImage]

    init?(image: CGImage) {
        guard image.width == Self.width, Self.heights.contains(image.height) else { return nil }
        func cell(_ row: Int, _ col: Int) -> CGImage? {
            image.cropping(to: CGRect(x: CGFloat(col) * Self.cell.width, y: CGFloat(row) * Self.cell.height,
                                      width: Self.cell.width, height: Self.cell.height))
        }
        let count = image.height / Int(Self.cell.height)
        rows = (0..<count).map { r in (9..<11).contains(r) ? [] : (0..<8).compactMap { cell(r, $0) } }
        look = (9..<11).flatMap { r in (0..<8).compactMap { cell(r, $0) } }
    }

    func has(_ row: AtlasRow) -> Bool {
        row.index < rows.count && !rows[row.index].isEmpty
    }

    func frame(_ row: AtlasRow, _ index: Int) -> CGImage? {
        guard has(row) else { return nil }
        let frames = rows[row.index]
        return frames[min(index, frames.count - 1)]
    }

    /// `pet.sprite` from config.json, else `~/.ironpet/pet/spritesheet.{webp,png}`, else the Ghost sheet bundled in
    /// the app (generated by `tools/make_pet.swift` at build time).
    static func loadDefault(sprite: String? = Config.load().config.pet.sprite) -> Atlas? {
        var candidates: [URL] = []
        if let sprite, !sprite.isEmpty {
            candidates.append(URL(fileURLWithPath: (sprite as NSString).expandingTildeInPath))
        }
        candidates += [Paths.petDir.appendingPathComponent("spritesheet.webp"),
                       Paths.petDir.appendingPathComponent("spritesheet.png")]
        if let bundled = Bundle.main.url(forResource: "spritesheet", withExtension: "png") { candidates.append(bundled) }
        for url in candidates {
            guard let image = NSImage(contentsOf: url),
                  let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil),
                  let atlas = Atlas(image: cg) else { continue }
            NSLog("ironpet: loaded pet atlas \(url.path)")
            return atlas
        }
        return nil
    }
}
