#!/usr/bin/env python3
"""Compiles prompts/<id>.md into Sources/IronPetCore/Prompts/BuiltInPromptsData.swift.

Run it after adding or editing a prompt. A test fails when the generated file is out of date.
A prompt is one Markdown file whose name is its id. Its text is the file without the final newline,
so a prompt written as one paragraph keeps the exact text it had as a Swift string.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "Sources/IronPetCore/Prompts/BuiltInPromptsData.swift"

entries = []
for prompt in sorted((root / "prompts").glob("*.md")):
    text = prompt.read_text()
    if text.endswith("\n"):
        text = text[:-1]
    if not text.strip():
        sys.exit(f"{prompt}: the prompt is empty")
    if '"""' in text or '\\#(' in text:
        sys.exit(f'{prompt}: contains """ or \\#(, which the generated Swift string cannot hold')
    entries.append((prompt.stem, text))

lines = [
    "// Generated by scripts/gen_prompts.py from prompts/*.md. Do not edit by hand.",
    "",
    "enum BuiltInPromptsData {",
    "    static let all: [(id: String, text: String)] = [",
]
for name, text in entries:
    lines.append(f'        ("{name}", #"""')
    lines.append(text)
    lines.append('"""#),')
lines += ["    ]", "}", ""]
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)} with {len(entries)} prompt(s)")
